package Variables;

class Variables {

    public static void main(String[] args) {

        System.out.println("01. Definition");
            /*Definition
            1. A variable is a named memory location used to store data.
            2. The value of a variable can change during program execution.
            3. Syntax: dataType variableName = value;
            */


        System.out.println("02. RULES FOR DECLARING VARIABLES");
            /*RULES FOR DECLARING VARIABLES
            1. Variable names can contain letters, digits, '_' and '$'.
            2. Variable names cannot start with a digit.
            3. Variable names cannot be Java keywords.
            4. Variable names are case-sensitive.
            5. Variable names should have meaningful names.
            */

        System.out.println("03. VARIABLE DECLARATION AND INITIALIZATION");
            /* VARIABLE DECLARATION AND INITIALIZATION
            1. Declaration: int age
            2. Initialization: age=25
            3. Declaration + Initialization:: int age = 25
            */
            int age = 25;
            System.out.println("Declaration: int age");
            System.out.println("Initialization: age=25");
            System.out.println("Declaration + Initialization:: int age = 25");


        System.out.println("04. TYPES OF VARIABLES");
             /* TYPES OF VARIABLES
                 1. Local Variable
                 2. Instance Variable
                 3. Static Variable
                 */
    }
}